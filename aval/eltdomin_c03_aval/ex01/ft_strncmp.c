#include <unistd.h>

int	ft_strncmp(char *s1, char *s2, unsigned int n)
{
	unsigned int	a;
	int				i;

	i = 0;
	a = 0;
	while ((s1[i] == s2[i]) && (s1[i] != '\0' && s2[i] != '\0') && a < n)
	{
		i++;
		a++;
	}
	if ((s1[i] > s2[i] || s1[i] < s2[i]) && n > a)
	{
		return (s1[i] - s2[i]);
	}
	else
	{
		return (0);
	}
}
