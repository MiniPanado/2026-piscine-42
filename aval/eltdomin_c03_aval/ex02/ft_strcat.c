#include <unistd.h>

char	*ft_strcat(char *dest, char *src)
{
	int	a;
	int	i;

	a = 0;
	i = 0;
	while (dest[a] != '\0')
		a++;
	while (*src != '\0')
	{
		dest[a + i] = *src;
		src++;
		i++;
	}
	dest[a + i] = '\0';
	return (dest);
}
