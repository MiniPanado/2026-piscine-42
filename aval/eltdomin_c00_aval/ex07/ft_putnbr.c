#include <unistd.h>

void ft_putnbr(int nb)
{
	
	if ( nb >= 10 )
	{
		ft_putnbr( nb / 10);
	}

	char digit = ( nb % 10 ) + '0';
	write(1, &digit, 1);
}

int main()
{
	ft_putnbr();
	return 0;
}

