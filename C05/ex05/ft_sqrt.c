int	ft_sqrt(int nb)
{
	int	i;

	if (nb < 0)
	{
		return (0);
	}
	if (nb <= 1)
	{
		return (nb);
	}
	i = 2;
	while (i < nb / i)
	{
		i++;
	}
	if (i * i == nb)
		return (i);
	return (0);
}
